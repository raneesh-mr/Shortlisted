// Bundles prompts/*.md into prompts/index.generated.ts. Cloudflare Workers have no
// filesystem at runtime, so prompts ship inside the code. The .md files stay the
// source of truth; this runs automatically before dev, build and test.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "prompts");
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".md"))
  .sort();

const entries = files.map((f) => {
  const raw = readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n");
  return `  ${JSON.stringify(f.replace(/\.md$/, ""))}: ${JSON.stringify(raw)},`;
});

writeFileSync(
  join(dir, "index.generated.ts"),
  [
    "// AUTO-GENERATED by scripts/gen-prompts.mjs. Do not edit; change the .md files instead.",
    "export const rawPrompts: Record<string, string> = {",
    ...entries,
    "};",
    "",
  ].join("\n"),
);
console.log(`gen-prompts: ${files.length} prompts`);
